import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash, randomBytes } from 'node:crypto';
import { parseEnv } from 'node:util';

export function tokenSql(token) {
  if (!/^[a-f0-9]{64,}$/.test(token || '')) throw new Error('Invalid intake token');
  const hash = createHash('sha256').update(token, 'utf8').digest('hex');
  return `-- Contains only a SHA-256 hash, never the intake token.\nbegin;\ninsert into private.contact_intake_tokens (singleton, token_hash)\nvalues (true, decode('${hash}', 'hex'))\non conflict (singleton) do nothing;\ndo $$\nbegin\n  if not exists (select 1 from private.contact_intake_tokens\n                 where singleton and token_hash = decode('${hash}', 'hex')) then\n    raise exception 'A different intake token is already configured. No token was replaced. Review the existing server configuration first.';\n  end if;\nend;\n$$;\ncommit;\n`;
}

function withoutTransaction(sql) {
  return sql.replace(/^begin;\r?\n/m, '').replace(/^commit;\s*$/m, '');
}

export async function prepareLocalSetup(root) {
  const envPath = path.join(root, '.env.local');
  let created = false;
  try {
    await fs.writeFile(envPath,
      `SUPABASE_URL=https://lykeruumioxbmcvryrnq.supabase.co\nSUPABASE_PUBLISHABLE_KEY=\nSUPABASE_INTAKE_TOKEN=${randomBytes(32).toString('hex')}\n`,
      { flag: 'wx', mode: 0o600 });
    created = true;
  } catch (error) { if (error.code !== 'EEXIST') throw error; }
  const env = parseEnv(await fs.readFile(envPath, 'utf8'));
  const token = tokenSql(env.SUPABASE_INTAKE_TOKEN);
  const source = path.join(root, 'supabase');
  const preflight = await fs.readFile(path.join(source, 'setup-preflight.sql'), 'utf8');
  const migrations = [];
  for (const name of ['20261019000000_kindler_contact_requests.sql', '20261019010000_single_administrator.sql']) {
    migrations.push(`-- Source: ${name}\n${withoutTransaction(await fs.readFile(path.join(source, 'migrations', name), 'utf8'))}`);
  }
  const full = `-- GENERATED by npm.cmd run setup:local. Fresh installation only.\n-- Existing project objects abort the entire transaction BEFORE changes.\n-- Does not create users, authorize administrators, or change Auth settings.\nbegin;\n${preflight}\n${migrations.join('\n')}\n${withoutTransaction(token)}\nnotify pgrst, 'reload schema';\ncommit;\n`;
  await fs.writeFile(path.join(source, 'SETUP.local.sql'), full, { mode: 0o600 });
  await fs.writeFile(path.join(source, 'TOKEN.local.sql'), token, { mode: 0o600 });
  return { created, keyPresent: Boolean(env.SUPABASE_PUBLISHABLE_KEY?.trim()) };
}
